// Writes the Lastbell ABI into the shared package so the keeper and web app use the exact compiled interface.
// Usage: npm run export-abi -w contracts (after `hardhat build`)
import { readFile, writeFile } from "node:fs/promises";

const artifact = JSON.parse(
  await readFile(new URL("../artifacts/contracts/Lastbell.sol/Lastbell.json", import.meta.url), "utf8"),
) as { abi: unknown[] };

const out = `// Generated by contracts/scripts/export-abi.ts. Do not edit by hand.
export const lastbellAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
await writeFile(new URL("../../shared/src/abi/lastbell.ts", import.meta.url), out);
console.log(`exported ${artifact.abi.length} ABI entries`);
